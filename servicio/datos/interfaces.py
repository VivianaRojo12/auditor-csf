"""C7. Interfaces de los adaptadores de acceso a datos y modelos.

Las capas superiores dependen solo de estas interfaces. Cambiar de base vectorial (Chroma por memoria,
FAISS o Qdrant) o de servidor de modelos implica escribir un adaptador nuevo, sin tocar las capas de arriba.
"""
from __future__ import annotations

from typing import Any, Protocol

from servicio.dominio import Fragmento, RespuestaModelo


class ServidorModelos(Protocol):
    def generar(self, modelo: str, mensajes: list[dict[str, str]], esquema: dict | None,
                tiempo_limite_s: float, opciones: dict[str, Any]) -> RespuestaModelo: ...
    def embeber(self, modelo: str, textos: list[str]) -> list[list[float]]: ...
    def estado(self) -> dict[str, Any]: ...
    def detalles_modelo(self, modelo: str) -> dict[str, Any]: ...


class BaseVectorial(Protocol):
    def agregar(self, fragmentos: list[Fragmento], vectores: list[list[float]]) -> None: ...
    def buscar(self, vector: list[float], k: int, filtro: dict | None = None) -> list[Fragmento]: ...
    def eliminar_documento(self, doc_id: str) -> int: ...
    def contar(self) -> int: ...
    def obtener(self, ids: list[str]) -> list[Fragmento]: ...
    def estado(self) -> dict[str, Any]: ...


class AlmacenDocumentos(Protocol):
    def guardar_documento(self, doc_id: str, nombre: str, formato: str, sha256: str,
                          fragmentos: int, contenido: bytes) -> None: ...
    def listar_documentos(self) -> list[dict[str, Any]]: ...
    def obtener_documento(self, doc_id: str) -> dict[str, Any] | None: ...
    def buscar_por_hash(self, sha256: str) -> dict[str, Any] | None: ...
    def eliminar_documento(self, doc_id: str) -> bool: ...
    def version_corpus(self) -> str: ...


class AlmacenCache(Protocol):
    def obtener_exacta(self, llave: str) -> dict[str, Any] | None: ...
    def guardar(self, llave: str, vector: list[float] | None, resultado: dict[str, Any],
                version_corpus: str, documentos: list[str]) -> None: ...
    def candidatos_semanticos(self, version_corpus: str) -> list[tuple[str, list[float], dict[str, Any], float]]: ...
    def invalidar_documento(self, doc_id: str) -> int: ...
    def purgar_version(self, version_vigente: str) -> int: ...
    def purgar_expiradas(self, ttl_s: float) -> int: ...
    def contar(self) -> int: ...
